function buildEan13(base12: string): string {
  let sum = 0;
  for (let i = 0; i < 12; i += 1) {
    const d = Number(base12[i]);
    sum += i % 2 === 0 ? d : d * 3;
  }
  const check = (10 - (sum % 10)) % 10;
  return `${base12}${check}`;
}

